"""
SQL syntax validation tests for combine_property_data macros using sqlglot.

These tests verify that the SQL generated by the multi-site cloning macros
is syntactically valid BigQuery SQL. They run without requiring a BigQuery
connection, making them fast and suitable for CI/CD.
"""

import pytest

sqlglot = pytest.importorskip("sqlglot", reason="sqlglot required for SQL syntax validation tests")


class TestGenerateCloneStatementSyntax:
    """Test that generate_clone_statement produces valid BigQuery SQL."""

    @pytest.mark.parametrize(
        "source_project,source_schema,source_table,dest_project,dest_schema,dest_table",
        [
            # Standard daily table
            (
                "my-source-project",
                "analytics_123456789",
                "events_20240101",
                "my-target-project",
                "combined_data",
                "events_20240101123456789",
            ),
            # Intraday table
            (
                "my-source-project",
                "analytics_123456789",
                "events_intraday_20240102",
                "my-target-project",
                "combined_data",
                "events_intraday_20240102123456789",
            ),
            # Different property ID
            (
                "my-source-project",
                "analytics_987654321",
                "events_20240103",
                "my-target-project",
                "combined_data",
                "events_20240103987654321",
            ),
            # Project names with numbers
            (
                "project-123",
                "analytics_111222333",
                "events_20240101",
                "project-456",
                "ga4_combined",
                "events_20240101111222333",
            ),
            # Underscores in project names
            (
                "my_source_project",
                "analytics_123456789",
                "events_20240101",
                "my_target_project",
                "combined_dataset",
                "events_20240101123456789",
            ),
        ],
    )
    def test_clone_statement_parses(
        self,
        source_project,
        source_schema,
        source_table,
        dest_project,
        dest_schema,
        dest_table,
    ):
        """Verify clone statement SQL parses as valid BigQuery."""
        # This matches the output of generate_clone_statement macro
        sql = f"CREATE OR REPLACE TABLE `{dest_project}.{dest_schema}.{dest_table}` CLONE `{source_project}.{source_schema}.{source_table}`;"

        # sqlglot should parse this without raising an exception
        parsed = sqlglot.parse(sql, read="bigquery")

        assert len(parsed) == 1, f"Expected 1 statement, got {len(parsed)}"
        assert parsed[0] is not None, "Parsed statement should not be None"


