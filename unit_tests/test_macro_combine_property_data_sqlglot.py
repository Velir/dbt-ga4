class TestCombinedStatementsSyntax:
    """Test that a batch of statements (as generated by combine_property_data) parses."""

    def test_full_clone_batch_parses(self):
        """
        Verify that a realistic batch of statements parses correctly.

        This simulates what combine_property_data generates: a create schema
        statement followed by multiple clone and drop statements.
        """
        sql = """
        CREATE SCHEMA IF NOT EXISTS `my-target-project.combined_data`;
        CREATE OR REPLACE TABLE `my-target-project.combined_data.events_20240101123456789` CLONE `my-source-project.analytics_123456789.events_20240101`;
        DROP TABLE IF EXISTS `my-target-project.combined_data.events_intraday_20240101123456789`;
        CREATE OR REPLACE TABLE `my-target-project.combined_data.events_intraday_20240102123456789` CLONE `my-source-project.analytics_123456789.events_intraday_20240102`;
        CREATE OR REPLACE TABLE `my-target-project.combined_data.events_20240101987654321` CLONE `my-source-project.analytics_987654321.events_20240101`;
        DROP TABLE IF EXISTS `my-target-project.combined_data.events_intraday_20240101987654321`;
        """

        # sqlglot should parse all statements
        parsed = sqlglot.parse(sql, read="bigquery")

        # Should have 6 statements
        assert len(parsed) == 6, f"Expected 6 statements, got {len(parsed)}"
        for i, stmt in enumerate(parsed):
            assert stmt is not None, f"Statement {i} should not be None"
